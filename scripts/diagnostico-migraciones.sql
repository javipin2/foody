  ('010 facturas',            to_regclass('public.facturas') IS NOT NULL),
  ('011 suscripciones_restaurante', to_regclass('public.suscripciones_restaurante') IS NOT NULL),
  ('013 usuarios.hash_contrasena',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='usuarios' AND column_name='hash_contrasena')),
  ('021 pedidos.factura_id',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='pedidos' AND column_name='factura_id')),
  ('026 cocinas',             to_regclass('public.cocinas') IS NOT NULL),
  ('027 pedidos.iva_porcentaje',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='pedidos' AND column_name='iva_porcentaje')),
  ('028 mesas_qr_token_min_len',
     EXISTS(SELECT 1 FROM pg_constraint WHERE conname='mesas_qr_token_min_len')),
