     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='recetas' AND column_name='tipo')),
  ('034 producto_items_incluidos', to_regclass('public.producto_items_incluidos') IS NOT NULL),
  ('035 productos.precio_para_llevar',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='productos' AND column_name='precio_para_llevar')),
