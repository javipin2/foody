     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='ingredientes' AND column_name='descontar_stock')),
  ('037 ingredientes.proveedor',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='ingredientes' AND column_name='proveedor')),
  ('041 pedidos.stock_descontado',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='pedidos' AND column_name='stock_descontado')),
  ('044 estados_promociones.codigo',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='estados_promociones' AND column_name='codigo')),
