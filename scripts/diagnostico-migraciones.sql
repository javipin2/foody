  VALUES
  ('002 usuarios',            to_regclass('public.usuarios') IS NOT NULL),
  ('003 dispositivos_cliente',to_regclass('public.dispositivos_cliente') IS NOT NULL),
  ('003 tokens_push_admin',   to_regclass('public.tokens_push_admin') IS NOT NULL),
