     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='pedido_items' AND column_name='estado_cobro')),
  ('047 pedidos.monto_pagado',
     EXISTS(SELECT 1 FROM information_schema.columns WHERE table_name='pedidos' AND column_name='monto_pagado')),
  ('047 pagos_pedido',        to_regclass('public.pagos_pedido') IS NOT NULL),
  ('047 pedidos_idempotencia',to_regclass('public.pedidos_idempotencia') IS NOT NULL),
  ('047 traslados_inventario',to_regclass('public.traslados_inventario') IS NOT NULL),
